/* 某一课有哪些手写的短文题（返回 [{passage, question}]） */
export function passageQuestionsFor(block, lessonNo) {
  const out = [];
  (PASSAGES[block] || []).forEach((p) => {
    (p.questions || []).forEach((q) => {
      if (q.lesson === lessonNo) out.push({ passage: p, question: q });
    });
  });
  return out;
}
